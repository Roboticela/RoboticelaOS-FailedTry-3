#!/usr/bin/env python3
"""Convert assets/logo.bmp into an assembly object (logo_embed.S) that is
linked into BOOTX64.EFI as the fallback boot logo.

The embedded image is only used when RoboBoot/logo.bmp is absent or invalid on
the EFI System Partition, so a missing runtime logo still yields the branded
boot screen. Symbols: embedded_logo_start, embedded_logo_end.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    src = os.path.join(ROOT, "assets", "logo.bmp")
    out_dir = os.path.join(ROOT, "build", "generated")
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, "logo_embed.S")

    with open(src, "rb") as f:
        data = f.read()

    with open(out, "w") as f:
        f.write("/* Auto-generated by tools/embedlogo.py -- DO NOT EDIT.\n")
        f.write(" * Fallback boot logo (BMP), embedded at link time. */\n")
        f.write(".section .rodata\n\n")
        f.write(".global embedded_logo_start\n")
        f.write(".balign 16\n")
        f.write("embedded_logo_start:\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            f.write(".byte " + ",".join("0x%02x" % b for b in chunk) + "\n")
        f.write(".global embedded_logo_end\n")
        f.write("embedded_logo_end:\n")
        f.write(".balign 16\n")
    print("wrote %s (%d bytes of logo)" % (out, len(data)))


if __name__ == "__main__":
    main()
